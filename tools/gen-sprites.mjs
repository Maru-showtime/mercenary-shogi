// 横に連続する同色を1つの rect にまとめて SVG にする
function toSvg(c) {
  const parts = [];
  for (let y = 0; y < SIZE; y++) {
    let x = 0;
    while (x < SIZE) {
      const color = c.g[y][x];
      if (color === null) {
        x += 1;
        continue;
      }
      let w = 1;
      while (x + w < SIZE && c.g[y][x + w] === color) w += 1;
      parts.push(`<rect x="${x}" y="${y}" width="${w}" height="1" fill="${color}"/>`);
      x += w;
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" shape-rendering="crispEdges">\n${parts.join("\n")}\n</svg>\n`;
}

