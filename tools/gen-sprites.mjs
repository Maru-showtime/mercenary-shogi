function canvas() {
  const g = Array.from({ length: SIZE }, () => Array(SIZE).fill(null));
  return {
    g,
    px(x, y, c) {
      if (x >= 0 && x < SIZE && y >= 0 && y < SIZE) g[y][x] = c;
    },
    rect(x, y, w, h, c) {
      for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) this.px(x + i, y + j, c);
    },
    // [y, x0, x1] の並びで塗る。曲線的な形を作りやすい
    spans(list, c) {
      for (const [y, x0, x1] of list) this.rect(x0, y, x1 - x0 + 1, 1, c);
    },
    diag(x, y, len, c, dx = 1, dy = -1) {
      for (let i = 0; i < len; i++) this.px(x + dx * i, y + dy * i, c);
    },
    // 既に塗られている画素の外側に輪郭を付ける
    outline(c) {
      const src = this.g.map((r) => r.slice());
      for (let y = 0; y < SIZE; y++) {
        for (let x = 0; x < SIZE; x++) {
          if (src[y][x] !== null) continue;
          const near =
            (y > 0 && src[y - 1][x]) ||
            (y < SIZE - 1 && src[y + 1][x]) ||
            (x > 0 && src[y][x - 1]) ||
            (x < SIZE - 1 && src[y][x + 1]);
          if (near) this.px(x, y, c);
        }
      }
    },
  };
}

// 大きな瞳。黒い面積を抑えて虹彩を広く取らないと、小さく描いたとき黒い点に見える
function eye(c, x, y, flip = false) {
  const { O, I1, I2, W } = C;
  const w = 7;
  // まつ毛（上は1列だけ）
  c.rect(x, y, w, 1, O);
  c.px(flip ? x + w - 1 : x, y - 1, O);
  // 虹彩（上が明るく下が濃い）
  c.rect(x, y + 1, w, 6, I1);
  c.rect(x, y + 4, w, 3, I2);
  // 左右の縁
  c.rect(x, y + 1, 1, 6, O);
  c.rect(x + w - 1, y + 1, 1, 6, O);
  // 瞳孔（小さめ）
  c.rect(x + 3, y + 3, 2, 3, O);
  // ハイライト
  c.rect(x + 1, y + 1, 2, 2, W);
  c.px(x + 5, y + 5, W);
  // 下まぶた
  c.rect(x + 1, y + 7, w - 2, 1, C.S3);
}

